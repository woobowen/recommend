"""Independent CPU readback of the trusted checkpoint produced by this experiment."""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import sys
import time


def tensor_sha(tensor):
    return hashlib.sha256(tensor.detach().cpu().contiguous().numpy().tobytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="Successful preflight run directory")
    parser.add_argument("--sid", type=Path, required=True, help="Bound semantic_ids.pt")
    args = parser.parse_args()
    t0 = time.monotonic()
    os.environ["CUDA_VISIBLE_DEVICES"] = ""
    os.environ.setdefault("OMP_NUM_THREADS", "4")
    os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "3")
    sys.path.insert(0, str(args.runtime.resolve() / "native"))
    import lightning as L
    from hydra.utils import instantiate
    from omegaconf import OmegaConf
    import torch

    stage = json.loads((args.output / "stage_result.json").read_text())
    ckpt_info = stage["checkpoint"]
    path = args.output / ckpt_info["path"]
    assert path.is_file() and path.resolve().is_relative_to(args.output.resolve())
    file_hash = hashlib.sha256()
    with path.open("rb") as fp:
        for block in iter(lambda: fp.read(1024 * 1024), b""):
            file_hash.update(block)
    assert file_hash.hexdigest() == ckpt_info["sha256"]
    assert path.stat().st_size == ckpt_info["bytes"]
    cfg = OmegaConf.load(args.output / "effective_config.yaml")
    assert cfg.seed == 42 and cfg.ckpt_path is None and cfg.model.eval_seed == 2026
    assert cfg.model.shuffle_embedding_on_test is False and cfg.model.top_k_for_generation == 10
    cfg.model.codebooks._args_[0].file_path = str(args.sid.resolve())
    L.seed_everything(cfg.seed, workers=True)
    model = instantiate(cfg.model)
    named = list(model.named_parameters())
    assert sum(param.numel() for _, param in named) == 13_128_064
    assert all(param.dtype == torch.float32 and param.requires_grad for _, param in named)
    assert model.get_embedding_table("encoder") is model.get_embedding_table("decoder")
    assert list(model.get_embedding_table("encoder").weight.shape) == [1024, 128]
    assert torch.equal(model.codebooks.cpu(), torch.load(args.sid, map_location="cpu", weights_only=True).T)
    initial = hashlib.sha256()
    for name, param in named:
        initial.update(name.encode() + b"\0")
        initial.update(param.detach().cpu().contiguous().numpy().tobytes())
    assert initial.hexdigest() == json.loads((args.output / "model.json").read_text())["initial_parameters_sha256"]
    events = [json.loads(line) for line in (args.output / "events.jsonl").read_text().splitlines()]
    (start,) = [item for item in events if item["event"] == "train_start"]
    assert start["step"] == start["optimizer_state_entries"] == 0
    first, last = [item for item in events if item["event"] == "optimizer_probe"]
    assert [(item["step"], item["microbatch"]) for item in (first, last)] == [(1, 16), (100, 1600)]
    names = dict(named)
    for item in (first, last):
        before, after = item["parameter_before_sha256"], item["parameter_after_sha256"]
        assert set(before) == set(after) == set(item["adam_before"]) == set(item["adam_after"])
        assert len(before) == 9 and all(before[name] != after[name] for name in before)
        assert set(item["adam_before"].values()) == {item["step"] - 1}
        assert set(item["adam_after"].values()) == {item["step"]}
        assert math.isfinite(item["loss_accumulation_scaled"])
        assert all(value is None or math.isfinite(value) for value in item["gradient_l2"].values())
        assert all(item["gradient_l2"][key] > 0 for key in before)
    assert all(tensor_sha(names[key]) == value for key, value in first["parameter_before_sha256"].items())
    (val_start,) = [item for item in events if item["event"] == "validation_start"]
    (val_end,) = [item for item in events if item["event"] == "validation_end"]
    assert val_start["step"] == val_end["step"] == 100
    assert val_start["microbatches"] == 1600 and val_end["batches"] == 24
    assert stage["mode"] == "preflight" and stage["shuffle_calls"] == 0
    assert sum(stage["expanded_microbatch"]["distribution"].values()) == 1600
    assert 0 < stage["expanded_microbatch"]["min"] <= stage["expanded_microbatch"]["max"] <= 128
    # The caller supplies the audited file generated by this run. Lightning's
    # full optimizer/callback payload requires its ordinary full deserializer.
    data = torch.load(path, map_location="cpu", weights_only=False)
    assert data["global_step"] == ckpt_info["step"] == stage["global_step"] == 100
    assert data["loops"] and data["state_dict"]
    saved = data["state_dict"]
    assert set(model.state_dict()) == set(saved)
    touched = model.load_state_dict(saved, strict=True)
    assert touched.missing_keys == touched.unexpected_keys == []
    assert all(torch.equal(value.cpu(), saved[key]) for key, value in model.state_dict().items())
    assert all(torch.isfinite(tensor).all() for tensor in saved.values() if tensor.is_floating_point())
    assert all(tensor_sha(saved[key]) == value for key, value in last["parameter_after_sha256"].items())
    loaded = hashlib.sha256()
    for name, tensor in sorted(model.state_dict().items()):
        loaded.update(json.dumps([name, str(tensor.dtype), list(tensor.shape)]).encode() + b"\0")
        loaded.update(tensor.detach().cpu().contiguous().numpy().tobytes())
    assert loaded.hexdigest() == ckpt_info["model_state_sha256"]
    for label in ("enabled", "disabled"):
        receipt = json.loads((args.output / f"reload_{label}.json").read_text())
        assert receipt["strict"] is True and receipt["missing"] == receipt["unexpected"] == []
        assert receipt["keys"] == len(saved)
        assert receipt["checkpoint_sha256"] == file_hash.hexdigest()
        assert receipt["model_state_sha256"] == loaded.hexdigest()

    (adam,) = data["optimizer_states"]
    (group,) = adam["param_groups"]
    assert len(group["params"]) == len(named)
    assert group["lr"] == 0.001 and group["weight_decay"] == 0.0001
    assert group["betas"] == (0.9, 0.999) and group["eps"] == 1e-8
    assert data["lr_schedulers"] == []
    parameter_names = dict(zip(group["params"], map(lambda item: item[0], named)))
    assert set(adam["state"]) <= set(parameter_names)
    missing_optimizer = sorted(parameter_names[key] for key in parameter_names.keys() - adam["state"].keys())
    assert all(name.endswith(("shared.weight", "embed_tokens.weight")) for name in missing_optimizer)
    steps = {}
    for idx, value in adam["state"].items():
        name = parameter_names[idx]
        assert value["exp_avg"].shape == value["exp_avg_sq"].shape == saved[name].shape
        assert torch.isfinite(value["exp_avg"]).all() and torch.isfinite(value["exp_avg_sq"]).all()
        assert (value["exp_avg_sq"] >= 0).all()
        steps[name] = int(value["step"].item())
    assert steps and set(steps.values()) == {100}
    for required in ("sep_token", "decoder.bos_token", "item_sid_embedding_table_encoder.weight"):
        assert required in steps
    assert len([name for name in steps if ".decoder_mlp." in name]) == 4

    callbacks = data["callbacks"]
    (checkpoint_key,) = [name for name in callbacks if name.startswith("ModelCheckpoint")]
    (early_key,) = [name for name in callbacks if name.startswith("EarlyStopping")]
    best_score = float(callbacks[checkpoint_key]["best_model_score"])
    assert math.isfinite(best_score) and best_score == ckpt_info["score"] == val_end["monitor"]
    assert "val/recall@5" in checkpoint_key and "val/recall@5" in early_key
    assert Path(callbacks[checkpoint_key]["best_model_path"]).name == path.name
    assert callbacks[early_key]["patience"] == 10 and callbacks[early_key]["wait_count"] == 0
    assert float(callbacks[early_key]["best_score"]) == best_score
    report = {"lightning": L.__version__, "torch": torch.__version__, "gpu": False,
              "sha256": file_hash.hexdigest(), "bytes": path.stat().st_size, "step": data["global_step"],
              "epoch": data["epoch"], "monitor": "val/recall@5", "best_model_score": best_score,
              "model_state_tensor_count": len(saved), "model_state_sha256": loaded.hexdigest(),
              "strict_load_fresh_instance": True, "strict_gpu_receipts_verified": 2,
              "steps_and_probe_microbatches": [[first["step"], first["microbatch"]], [last["step"], last["microbatch"]]],
              "first_probe_bound_to_fresh_model": True, "last_probe_bound_to_checkpoint": True,
              "validation_microbatch": val_start["microbatches"], "val_batches": val_end["batches"],
              "initial_parameter_sha256": initial.hexdigest(),
              "optimizer_state_count": len(adam["state"]), "optimizer_unique_steps": sorted(set(steps.values())),
              "optimizer_no_state": missing_optimizer, "callback_keys": sorted(callbacks),
              "elapsed_seconds": time.monotonic() - t0}
    print(json.dumps(report, indent=2))

if __name__ == "__main__":
    main()
